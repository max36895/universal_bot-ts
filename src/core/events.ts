/**
 * Универсальный событийный слой фреймворка.
 *
 * Адаптеры платформ приводят свои типы апдейтов к единому перечню `TEventType`
 * и записывают его в `controller.eventType`. Обработчики, зарегистрированные через
 * `bot.addEvent(...)`, вызываются до поиска шагов и команд — декларативный
 * роутинг по типу события без привязки к одной платформе.
 *
 * Ядро НЕ знает, какие события поддерживает конкретная платформа: адаптер
 * объявляет их сам через `supportedEvents` (см. `BasePlatform`), поэтому
 * кастомные платформы (WeChat, Slack и др., подключённые через `BasePlatform`)
 * автоматически участвуют в валидации и работают со событийным слоем наравне
 * со встроенными.
 *
 * Событие «message» — обычный текстовый ввод — является значением по умолчанию:
 * если адаптер не выставил `eventType`, контроллер получает `'message'`.
 * Обработчик на `'message'` вызывается для всех текстовых запросов на любой
 * платформе: фильтрации обработчиков по `supportedEvents` при обработке запроса
 * нет — `supportedEvents` используется только для предупреждения при
 * регистрации обработчика в `bot.addEvent(...)`.
 */

/**
 * Универсальные типы событий платформ.
 *
 * Перечень — общий знаменатель для встроенных платформ; адаптер выставляет
 * только те значения, которые физически возможны на его платформе
 * (см. `supportedEvents` у каждого адаптера). Кастомная платформа может
 * использовать любое значение отсюда при наследовании `BasePlatform`.
 */
export type TEventType =
    /**
     * Текстовое сообщение пользователя (в том числе голосовой ввод, распознанный платформой).
     */
    | 'message'
    /**
     * Сообщение с фотографией.
     */
    | 'photo'
    /**
     * Сообщение с аудио/голосовым сообщением.
     */
    | 'voice'
    /**
     * Сообщение с видео.
     */
    | 'video'
    /**
     * Сообщение с файлом/документом.
     */
    | 'document'
    /**
     * Сообщение с геолокацией.
     */
    | 'location'
    /**
     * Сообщение с контактом.
     */
    | 'contact'
    /**
     * Сообщение со стикером.
     */
    | 'sticker'
    /**
     * Нажатие inline/callback-кнопки (payload кнопки).
     */
    | 'callback'
    /**
     * Inline-запрос (пользователь печатает «@бот …» в поле ввода).
     */
    | 'inline'
    /**
     * Отредактированное сообщение пользователя.
     */
    | 'message_edited'
    /**
     * Сообщение/пост в канале.
     */
    | 'channel_post'
    /**
     * Начало диалога: первый вход в навык/бота (deep-link payload в `controller.payload`).
     */
    | 'start'
    /**
     * Подписка пользователя на бота.
     */
    | 'subscribed'
    /**
     * Отписка пользователя от бота.
     */
    | 'unsubscribed'
    /**
     * Завершение привязки аккаунта (Яндекс.Диалоги account_linking).
     */
    | 'auth'
    /**
     * Результат оценки приложения.
     */
    | 'rating';

/**
 * Все допустимые универсальные события (для валидации имён).
 */
export const ALL_EVENT_TYPES: readonly TEventType[] = [
    'message',
    'photo',
    'voice',
    'video',
    'document',
    'location',
    'contact',
    'sticker',
    'callback',
    'inline',
    'message_edited',
    'channel_post',
    'start',
    'subscribed',
    'unsubscribed',
    'auth',
    'rating',
];

/**
 * Проверяет, что строка — корректное универсальное событие.
 * @param event Проверяемое значение
 * @returns true, если имя события известно фреймворку
 */
export function isEventType(event: string): event is TEventType {
    return (ALL_EVENT_TYPES as readonly string[]).includes(event);
}
