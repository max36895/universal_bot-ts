import { IAppParam } from 'umbot';

/**
 * Параметры демо-приложения.
 *
 * В этом демо вся логика описана командами (`addCommand`) в `src/index.ts`,
 * поэтому собственные интенты не нужны — `intents: null`. Тексты ниже —
 * запасные ответы фреймворка на случай, если ни одна команда не сработает:
 * `empty_text` подставит дефолтный контроллер, `welcome_text`/`help_text`
 * используются для стандартных сценариев без команд. Команды в `index.ts`
 * перекрывают эти сценарии своими текстами, но конфиг показывает, где живут
 * дефолтные ответы.
 */
export default function appParams(): IAppParam {
    return {
        welcome_text:
            'Добро пожаловать в кофейню «У Бота»! Скажите «помощь», чтобы узнать, что я умею.',
        help_text: 'Я показываю меню, принимаю заказы и запоминаю любимый напиток.',
        empty_text: 'Я вас не понимаю. Скажите «помощь», чтобы узнать мои команды.',
        intents: null,
    };
}
