/**
 * Тесты логики меток «лучший/паритет» compare-стендов
 * (benchmark/comparison/markRow.js, используется runner.js).
 *
 * История бага (найден при аудите честности): старая markRow вешала
 * «← лучший» любому единственному лидеру, не проверяя величину отрыва —
 * на MAX «6 команд» 1.5 против 1.4 мкс (0.1 мкс — втрое ниже собственного
 * порога шума WIN_ABS_US) помечалось победой max-bot-api, хотя по правилам
 * стенда это паритет. Логика вынесена в тестируемый модуль по образцу
 * umVerdict.js и зафиксирована контрактом:
 *   - победа: отрыв лучшего от ВТОРОГО места ≥ WIN_ABS_US мкс И ≥ WIN_REL;
 *   - паритет: отставание от лучшего < WIN_ABS_US мкс ИЛИ < WIN_REL.
 */
import { markRow, WIN_REL, WIN_ABS_US } from '../../benchmark/comparison/markRow';

type Row = { name: string; winner: boolean; tie: boolean };

/** Обёртка входа: стенд кладёт в row.data объекты {p50Us, ...}. */
function mark(values: Record<string, number>): Row[] {
    const data = Object.fromEntries(
        Object.entries(values).map(([name, p50Us]) => [name, { p50Us }]),
    );
    return markRow(Object.keys(data), data) as Row[];
}

/** Компактная метка строки: W — лучший, T — паритет, «-» — вне борьбы. */
function marks(values: Record<string, number>): string {
    return mark(values)
        .map((m) => (m.winner ? 'W' : m.tie ? 'T' : '-'))
        .join(',');
}

describe('benchmark comparison: markRow', () => {
    it('пороги определены: 5% и 0.3 мкс', () => {
        expect(WIN_REL).toBe(1.05);
        expect(WIN_ABS_US).toBe(0.3);
    });

    // Баг из аудита: 0.1 мкс (7% относительных) — паритет, не победа.
    it('отрыв 0.1 мкс ниже порога шума — паритет (MAX 6 команд: 1.5/1.4)', () => {
        expect(marks({ umbot: 1.5, max: 1.4 })).toBe('T,T');
        expect(marks({ umbot: 1.6, max: 1.5 })).toBe('T,T');
    });

    // Относительно маленький, но абсолютный отрыв > 0.3 мкс: по правилам
    // стенда (оба порога одновременно) — паритет: 1% относительных не
    // позволяет отличить победу от шума на большой базе.
    it('0.4 мкс на большой базе (40/39.6 мкс = 1%) — паритет: не пробит относительный порог', () => {
        expect(marks({ a: 39.6, b: 40 })).toBe('T,T');
    });

    it('отрыв, пробивающий оба порога — победа (VK 6 exact: 1.6/1.1 у vk-io)', () => {
        expect(marks({ umbot: 1.6, 'vk-io': 1.1 })).toBe('-,W');
    });

    it('ровно на границе порогов (2.2/1.9: 0.3 мкс и 16%) — победа', () => {
        expect(marks({ umbot: 2.2, viber: 1.9 })).toBe('-,W');
    });

    it('равные p50 — паритет у обоих', () => {
        expect(marks({ umbot: 2.4, 'vk-io': 2.4 })).toBe('T,T');
    });

    it('трое: лидер с уверенным отрывом, остальные сражаются между собой', () => {
        // Лидер 1.0; 2.05 и 2.1 отстают от лидера >0.3мкс и >5% — им «-».
        expect(marks({ a: 1.0, b: 2.05, c: 2.1 })).toBe('W,-,-');
        // Победа лидера над вторым недостаточна (0.04 мкс) — все в паритете.
        expect(marks({ a: 2.0, b: 2.04, c: 9.9 })).toBe('T,T,-');
    });

    it('победа засчитывается и против третьего места, если второй рядом с лидером', () => {
        // a и b в паритете между собой (0.05 мкс), но оба на 3+ мкс впереди c:
        // лидер не может «победить» — паритет полосы поглощает метку.
        expect(marks({ a: 2.0, b: 2.05, c: 9.9 })).toBe('T,T,-');
    });

    // Регресс на старое поведение: единственный лидер с микроскопическим
    // отрывом НЕ должен получать «лучший».
    it('0.05 мкс отрыва (5.0/4.95) — паритет, а не победа лидера', () => {
        expect(marks({ umbot: 4.95, x: 5.0 })).toBe('T,T');
    });
});
