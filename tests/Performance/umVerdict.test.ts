/**
 * Тесты логики вердикта benchmark/um.js (npm run comparison).
 *
 * Ключевые случаи:
 * 1. Равенство по памяти (0.00 KB) при времени −99% (сценарий ping) — «++ лучше».
 * 2. Время +190% при шумовом «улучшении» памяти (−0.002 КБ) — «-- уступаем»:
 *    шум памяти не маскирует просадку времени.
 *
 * Логика вынесена в модуль benchmark/umVerdict.js, чтобы её можно было
 * тестировать без запуска самого бенчмарка.
 */
import { getVerdict, MEM_NOISE_KB } from '../../benchmark/umVerdict';

describe('benchmark um.js: getVerdict', () => {
    // Время −99%, память 0.00 — это победа, а не «уступаем».
    it('время лучше на −99% при нулевой памяти дает «++ лучше», а не «уступаем»', () => {
        expect(getVerdict(-99.17, 0.0)).toBe('++ лучше');
    });

    it('время хуже на +166% при нулевой памяти дает «-- уступаем»', () => {
        expect(getVerdict(165.97, 0.0)).toBe('-- уступаем');
    });

    // Шумовое улучшение памяти не должно маскировать просадку времени.
    it('время хуже на +190% при шумовой памяти (−0.002 КБ) дает «-- уступаем»', () => {
        expect(getVerdict(190.47, -0.002)).toBe('-- уступаем');
    });

    it('шумовой порог памяти определен и больше нуля', () => {
        expect(MEM_NOISE_KB).toBeGreaterThan(0);
    });

    it('паритет: время в пределах ±10% при шумовой памяти — «== паритет»', () => {
        expect(getVerdict(8, 0.0)).toBe('== паритет');
        expect(getVerdict(-8, 0.05)).toBe('== паритет');
    });

    it('небольшая просадка времени до 20% при шумовой памяти — «допустимо»', () => {
        expect(getVerdict(15, 0.0)).toBe('+- допустимо*');
    });

    it('просадка времени 30% при шумовой памяти — «уступаем»', () => {
        expect(getVerdict(30, 0.0)).toBe('-- уступаем');
    });

    it('лучше по времени и памяти — «++ лучше»', () => {
        expect(getVerdict(-50, -10)).toBe('++ лучше');
    });

    it('быстрее, но память значимо хуже — «допустимо» (компромисс)', () => {
        expect(getVerdict(-50, 5)).toBe('+- допустимо*');
    });

    it('медленнее вдвое при лучшей памяти — все равно «уступаем» (время главнее)', () => {
        expect(getVerdict(50, -10)).toBe('-- уступаем');
    });

    it('оба в порогах — «допустимо»', () => {
        expect(getVerdict(5, 25)).toBe('+- допустимо**');
    });

    it('память за порогом 30 КБ — «уступаем»', () => {
        expect(getVerdict(5, 35)).toBe('-- уступаем');
    });
});
